def _bare(s) -> str:
    s = str(s).strip().upper()
    return s.split(":", 1)[1] if ":" in s else s


# ================================================================= Universe B gate
def build_universe_b_gate() -> Tuple[pd.DataFrame, dict]:
    """(symbol, date) -> adv20_turnover, hist_ok, univ_b_ok  over the fresh pool.

    ADV20 turnover uses the identical causal formula as the originating diagnostic
    (tools/sub9_research/diag_universe_expectancy_by_era.build_adv_panel):
        turnover = close * volume ; rolling(20, min_periods=15).mean().shift(1)

    History gate: for signal date D let T(D) be the master-calendar sessions t with
    D - 18 months <= t < D. A symbol passes iff it has bars on >= 90% of T(D).
    The master calendar is every distinct session in clean_daily_from5m.feather, so
    the gate measures presence in the SAME archive the backtests replay.
    """
    d = pd.read_feather(CLEAN_DAILY)
    d["symbol"] = d["symbol"].map(_bare)
    d["date"] = pd.to_datetime(d["date"])
    d = d.sort_values(["symbol", "date"]).reset_index(drop=True)

    d["turnover"] = d["volume"] * d["close"]
    g = d.groupby("symbol", sort=False)
    d["adv20_turnover"] = (
        g["turnover"].transform(lambda s: s.rolling(20, min_periods=15).mean())
        .groupby(d["symbol"]).shift(1)
    )

    cal = pd.DatetimeIndex(sorted(d["date"].unique()))
    cal_pos = {t: i for i, t in enumerate(cal)}
    syms = sorted(d["symbol"].unique())
    spos = {s: i for i, s in enumerate(syms)}

    pres = np.zeros((len(syms), len(cal)), dtype=np.int32)
    pres[d["symbol"].map(spos).values, d["date"].map(cal_pos).values] = 1
    cum = np.cumsum(pres, axis=1)
    cum_pad = np.hstack([np.zeros((len(syms), 1), dtype=cum.dtype), cum])  # [:, i] = through i-1

    start_idx = np.searchsorted(cal.values, (cal - pd.DateOffset(months=HIST_MONTHS)).values, "left")
    expected = np.arange(len(cal)) - start_idx
    counts = cum_pad[:, np.arange(len(cal))] - cum_pad[:, start_idx]
    hist_ok = (expected[None, :] > 0) & (counts >= HIST_COVERAGE * expected[None, :])

    fpos = np.where((cal >= pd.Timestamp(FRESH_START)) & (cal <= pd.Timestamp(FRESH_END)))[0]
    gate = pd.DataFrame(hist_ok[:, fpos], index=syms, columns=cal[fpos]).stack().rename("hist_ok")
    gate = gate.reset_index()
    gate.columns = ["symbol", "date", "hist_ok"]
    gate = gate.merge(d[["symbol", "date", "adv20_turnover"]], on=["symbol", "date"], how="left")
    # A symbol-day with no live causal ADV20 cannot be VERIFIED under the ceiling ->
    # it fails Universe B. Conservative and stated up front.
    gate["turnover_ok"] = gate["adv20_turnover"].notna() & (gate["adv20_turnover"] <= TURNOVER_CEILING_INR)
    gate["univ_b_ok"] = gate["turnover_ok"] & gate["hist_ok"]

    meta = {
        "panel_symbols": len(syms),
        "master_calendar_sessions": len(cal),
        "fresh_sessions": len(fpos),
        "expected_sessions_in_18m_lookback": [int(expected[fpos].min()), int(expected[fpos].max())],
        "symbols_passing_history_gate_mean": float(hist_ok[:, fpos].sum(0).mean()),
        "fresh_symbol_days": int(len(gate)),
        "share_turnover_ok": float(gate["turnover_ok"].mean()),
        "share_hist_ok": float(gate["hist_ok"].mean()),
        "share_univ_b_ok": float(gate["univ_b_ok"].mean()),
    }
    return gate, meta


