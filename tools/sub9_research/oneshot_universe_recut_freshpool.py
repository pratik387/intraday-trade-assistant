# ================================================================= statistics (brief §7)
def _pf(x: np.ndarray) -> float:
    w, l = x[x > 0].sum(), -x[x < 0].sum()
    return float(w / l) if l > 0 else (np.inf if w > 0 else np.nan)


def _stats(df: pd.DataFrame) -> dict:
    if df.empty:
        return {"n": 0, "exp_bps": np.nan, "net_pf": np.nan, "wr_pct": np.nan, "net_inr": 0.0}
    net = df["net_pnl_inr"].values
    return {
        "n": int(len(df)),
        "exp_bps": float(df["net_bps"].mean()),
        "net_pf": _pf(net),
        "wr_pct": float((net > 0).mean() * 100),
        "net_inr": float(net.sum()),
    }


def compute_outcomes(trades: pd.DataFrame) -> Tuple[pd.DataFrame, dict, str, List[str]]:
    """Called ONLY after the power gate passes (brief §6)."""
    trades = trades.copy()
    trades["net_bps"] = trades["net_pnl_inr"] / trades["notional_inr"] * 10_000.0

    rows = []
    for setup, g in trades.groupby("setup"):
        for uni, sub in (("A", g), ("B", g[g["univ_b_ok"]])):
            r = {"level": "setup", "unit": setup, "cluster": CLUSTER[setup], "universe": uni}
            r.update(_stats(sub))
            rows.append(r)
    for cl, g in trades.groupby("cluster"):
        for uni, sub in (("A", g), ("B", g[g["univ_b_ok"]])):
            r = {"level": "cluster", "unit": cl, "cluster": cl, "universe": uni}
            r.update(_stats(sub))
            rows.append(r)
    for uni, sub in (("A", trades), ("B", trades[trades["univ_b_ok"]])):
        r = {"level": "pooled", "unit": "ALL", "cluster": "ALL", "universe": uni}
        r.update(_stats(sub))
        rows.append(r)
    res = pd.DataFrame(rows)

    pa = res[(res.level == "pooled") & (res.universe == "A")].iloc[0]
    pb = res[(res.level == "pooled") & (res.universe == "B")].iloc[0]

    # majority test on DECISION UNITS = clusters (multiday capitulation counts ONCE),
    # restricted to units with n >= 15 in BOTH universes.
    units, notes = [], []
    for cl, g in res[res.level == "cluster"].groupby("unit"):
        a = g[g.universe == "A"].iloc[0]
        b = g[g.universe == "B"].iloc[0]
        eligible = (a["n"] >= MIN_N_FOR_DECISION) and (b["n"] >= MIN_N_FOR_DECISION)
        units.append({"unit": cl, "n_A": a["n"], "n_B": b["n"], "exp_bps_A": a["exp_bps"],
                      "exp_bps_B": b["exp_bps"], "eligible": eligible,
                      "B_better": bool(eligible and b["exp_bps"] > a["exp_bps"])})
    ut = pd.DataFrame(units)
    elig = ut[ut["eligible"]]
    majority = bool(len(elig) and elig["B_better"].sum() * 2 > len(elig))

    ea, eb = float(pa["exp_bps"]), float(pb["exp_bps"])
    rel = abs(eb - ea) / abs(ea) if ea != 0 else np.inf

    # Precedence FIXED before any number was seen: the +/-10% band is the more
    # specific rule and is evaluated first, so a noise-level shortfall reads as
    # NO CHANGE rather than REJECT (the band exists for exactly that purpose).
    if rel <= NO_CHANGE_BAND:
        verdict = "no_change"
        notes.append(f"pooled B within +/-{NO_CHANGE_BAND:.0%} of A ({rel:.1%}) -> NO CHANGE (§7)")
    elif eb > ea and float(pb["net_pf"]) >= ADOPT_MIN_PF_B and majority:
        verdict = "adopt"
        notes.append("B > A, B pooled net PF >= 1.10, and B better in a majority of eligible units")
    elif eb < ea:
        verdict = "reject"
        notes.append(f"pooled B expectancy < A by {rel:.1%} (outside the +/-10% band)")
    else:
        verdict = "no_change"
        notes.append(f"B > A by {rel:.1%} but PF_B={pb['net_pf']:.3f} (>=1.10? "
                     f"{float(pb['net_pf']) >= ADOPT_MIN_PF_B}) / majority={majority} -> NO CHANGE")

    summary = {
        "pooled_A": {k: (None if pd.isna(pa[k]) else float(pa[k])) for k in ("n", "exp_bps", "net_pf", "wr_pct", "net_inr")},
        "pooled_B": {k: (None if pd.isna(pb[k]) else float(pb[k])) for k in ("n", "exp_bps", "net_pf", "wr_pct", "net_inr")},
        "rel_change_exp": float(rel) if np.isfinite(rel) else None,
        "majority_units_eligible": int(len(elig)),
        "majority_units_B_better": int(elig["B_better"].sum()) if len(elig) else 0,
        "majority_test": majority,
    }
    return res, summary, verdict, notes, ut


