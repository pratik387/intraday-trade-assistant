_BV_CACHE = ROOT / "reports" / "sub9_sanity" / "_below_vwap_freshpool_raw_sanity.csv"


def gen_below_vwap_volume_revert_long() -> pd.DataFrame:
    """MACHINERY: tools/sub9_research/sanity_below_vwap_volume_revert_long.run_window
    for the raw signal population, THEN the SHIPPED cell lock from
    tools/sub9_research/below_vwap_volume_revert_long_cell_lock.json applied on top:
      * 3D cell_filter  cap_segment=unknown x vol_ratio_bin=gte_10 x hhmm_bucket=afternoon_1300_1500
      * locked exit grid t1=1.5R / t2=2.0R / sl=1.0R / ts=14:30 / partial_50_no_trail,
        re-simulated with tools/methodology/cell_sweep._row_simulate (the same resim
        tools/sub9_research/apply_lock_below_vwap_oos_ho.py uses to apply this lock).
    The raw sanity population is NOT the mechanism we run — it is ~100x the production
    fire rate — so scoring it would be an unfaithful replication.

    run_window's _load_window has no lookback pad and vol_ratio needs rolling(20,
    min_periods=20) per (symbol, hhmm), so the harness is driven over
    2026-03-02..2026-07-24 and the output is then restricted to fresh-pool signal
    dates. That gives fresh-pool signals the same fully-warm baseline a mid-window
    signal gets in the original windows; no threshold or rule is altered.

    COST MODEL: calc_fee (MIS intraday, tools/sub7_validation/build_per_setup_pnl).
    NOTIONAL: entry_price * qty (Rs 1,000 risk-based sizing).
    """
    import json as _json
    from tools.methodology.cell_sweep import CellSweepConfig, GridEntry, _row_simulate
    from tools.sub7_validation.build_per_setup_pnl import calc_fee

    if _BV_CACHE.exists():
        t = pd.read_csv(_BV_CACHE)
        print(f"     (reusing cached raw sanity population {_BV_CACHE.name}: {len(t)} rows)")
    else:
        import tools.sub9_research.sanity_below_vwap_volume_revert_long as m
        m.WINDOWS["fresh"] = (date(2026, 3, 2), FRESH_END)
        t = m.run_window("fresh")
        if t is None or t.empty:
            return pd.DataFrame()
        _BV_CACHE.parent.mkdir(parents=True, exist_ok=True)
        t.to_csv(_BV_CACHE, index=False)

    t["signal_date"] = pd.to_datetime(t["signal_date"])
    t = t[(t["signal_date"] >= pd.Timestamp(FRESH_START))
          & (t["signal_date"] <= pd.Timestamp(FRESH_END))].copy()
    n_raw = len(t)

    lock = _json.loads(
        (ROOT / "tools" / "sub9_research" / "below_vwap_volume_revert_long_cell_lock.json")
        .read_text(encoding="utf-8"))
    cf = {k: v for k, v in lock["cell_filter"].items() if not k.startswith("comment")}
    for k, v in cf.items():
        t = t[t[k] == v]
    n_cell = len(t)

    gspec = lock["grid"]
    grid = GridEntry(label=gspec["label"], ts_hhmm=int(gspec["ts_hhmm"]),
                     partial_mode=gspec["partial_mode"], t1=float(gspec["t1_R"]),
                     t2=float(gspec["t2_R"]), sl=float(gspec["sl_R"]))
    cfg = CellSweepConfig(side="LONG", target_unit="R", grid=[grid],
                          dim_pool=list(cf.keys()))
    close_col = f"close_at_{int(gspec['ts_hhmm'])}"
    t = t.dropna(subset=[close_col, "mfe_r", "mae_r", "R_per_share"])
    nets = [_row_simulate(r, cfg, grid, close_col, calc_fee) for _, r in t.iterrows()]
    t = t.assign(net_pnl_inr=nets).dropna(subset=["net_pnl_inr"])
    print(f"     cell lock: raw fresh-pool signals {n_raw} -> 3D cell {n_cell} -> "
          f"locked-grid resim {len(t)}")
    t["notional_inr"] = t["entry_price"].astype(float) * t["qty"].astype(float)
    return t[["signal_date", "symbol", "net_pnl_inr", "notional_inr"]]


def gen_or_window_failure_fade_short() -> pd.DataFrame:
    """MACHINERY: tools/sub9_research/sanity_or_window_failure_fade — its own
    _load_5m_for_month / _cap_segment / _is_mis_eligible / _simulate_day driven over
    the fresh-pool months. This reproduces main()'s trade-generation loop verbatim
    (main() itself only adds printing and CSV writing).
    COST MODEL: calc_fee (MIS intraday) inside _path_walk.
    NOTIONAL: entry_price * qty (Rs 1,000 risk-based sizing).
    """
    import tools.sub9_research.sanity_or_window_failure_fade as m
    m.WINDOW_START, m.WINDOW_END, m.WINDOW_LABEL = FRESH_START, FRESH_END, "fresh"
    rows: List[dict] = []
    for (y, mm) in m._months_in_window():
        mdf = m._load_5m_for_month(y, mm)
        if mdf.empty:
            continue
        mdf["d"] = mdf["date"].dt.date
        mdf = mdf[(mdf["d"] >= m.WINDOW_START) & (mdf["d"] <= m.WINDOW_END)]
        if mdf.empty:
            continue
        syms = set(mdf["symbol"].unique())
        cap = {s: m._cap_segment(s) for s in syms}
        mis = {s: m._is_mis_eligible(s) for s in syms}
        keep = {s for s in syms if cap.get(s) in m.ALLOWED_CAPS and mis.get(s)}
        mdf = mdf[mdf["symbol"].isin(keep)]
        if mdf.empty:
            continue
        print(f"    or_window {y:04d}-{mm:02d}: {mdf['symbol'].nunique()} symbols, {mdf['d'].nunique()} days", flush=True)
        for (sym, dd), grp in mdf.groupby(["symbol", "d"], sort=False):
            tr = m._simulate_day(sym, grp.sort_values("date").reset_index(drop=True), cap.get(sym, "unknown"))
            if tr is not None:
                rows.append(tr)
        del mdf
    if not rows:
        return pd.DataFrame()
    t = pd.DataFrame(rows)
    t = t.rename(columns={"trade_date": "signal_date", "net_pnl": "net_pnl_inr"})
    t["notional_inr"] = t["entry_price"].astype(float) * t["qty"].astype(float)
    return t[["signal_date", "symbol", "net_pnl_inr", "notional_inr"]]


def gen_multiday_capitulation() -> Dict[str, pd.DataFrame]:
    """MACHINERY: tools/sub9_research/multiday_target_exit_study.build_trades (the
    exact selection used by monster_conditioning_validation to produce the BASELINE
    ledgers the diagnostic read) + its baseline hold-to-close geometry.
    COST MODEL: calc_fee_mtf at Rs 1,00,000 margin x 2.79 leverage.
    NOTIONAL: MARGIN * LEV = Rs 2,79,000 (constant, as in the baseline ledger).
    Runs entirely on clean_daily_from5m.feather, which covers the fresh pool.
    """
    from multiday_target_exit_study import CLEAN, CELLS, MARGIN, LEV, load_eligible, build_trades
    from monster_conditioning_validation import net_pnl_row

    dd = pd.read_feather(CLEAN)
    dd["date"] = pd.to_datetime(dd["date"])
    dd["bare"] = dd["symbol"].astype(str).str.replace("NSE:", "", regex=False).str.upper()
    elig = load_eligible()

    out: Dict[str, pd.DataFrame] = {}
    for name, (mode, params) in CELLS.items():
        sel, K = build_trades(dd, elig, mode, params)
        sel = sel[(sel["date"] >= pd.Timestamp(FRESH_START)) & (sel["date"] <= pd.Timestamp(FRESH_END))].copy()
        if sel.empty:
            out[name] = pd.DataFrame()
            continue
        sel["net_pnl_inr"] = [net_pnl_row(e, x, K + 1)
                              for e, x in zip(sel["open_next"].values, sel["close_exit"].values)]
        sel["signal_date"] = pd.to_datetime(sel["date"])
        sel["notional_inr"] = MARGIN * LEV
        out[name] = sel[["signal_date", "symbol", "net_pnl_inr", "notional_inr"]].reset_index(drop=True)
        print(f"    {name}: {len(out[name])} fresh-pool fires (K={K})", flush=True)
    return out


